const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const code=fs.readFileSync('tools/game-adapter.cjs','utf8');
const view=code.slice(code.indexOf('function view(install)'),code.indexOf('function action('));
let calls=0;
const context={document:{querySelector:q=>q==='#select.show #pick-view:not([hidden])'?{}:null},window:{__thor:{navigate:x=>x==='right'}}};
vm.createContext(context);vm.runInContext(view,context);
const snapshot=context.view(()=>calls++);
assert.equal(snapshot.online,false);assert.equal(snapshot.characterSelect,true);assert.equal(snapshot.nativeMenu,'pick');assert.equal(calls,1);
const action=code.slice(code.indexOf('function action('),code.indexOf('function valid('));
vm.runInContext(action,context);
assert.equal(context.action({type:'nav',value:'right'}),true);
assert.equal(context.action({type:'combat',value:'attack'}),false);
console.log('Character selection forwards navigation without enabling combat actions.');
